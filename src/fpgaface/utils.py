from __future__ import annotations

import json
import os
import random

import numpy as np

# Where Kaggle mounts attached datasets; scripts search here when a path is not given.
DEFAULT_SEARCH_ROOTS = ("/kaggle/input", os.path.expanduser("~/data"), "data")


def seed_everything(seed: int = 0) -> None:
    import torch

    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)


def find_file(name: str, roots=DEFAULT_SEARCH_ROOTS) -> str | None:
    """First file called `name` under any of `roots` (recursive)."""
    for root in roots:
        if not os.path.isdir(root):
            continue
        for dirpath, _, files in os.walk(root):
            if name in files:
                return os.path.join(dirpath, name)
    return None


def find_dir(name: str, roots=DEFAULT_SEARCH_ROOTS, must_contain: str | None = None) -> str | None:
    """First directory called `name` under `roots`, optionally containing entry `must_contain`."""
    for root in roots:
        if not os.path.isdir(root):
            continue
        for dirpath, dirs, _ in os.walk(root):
            if name in dirs:
                cand = os.path.join(dirpath, name)
                if must_contain is None or os.path.exists(os.path.join(cand, must_contain)):
                    return cand
    return None


def save_json(obj, path: str) -> None:
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w") as f:
        json.dump(obj, f, indent=2)


def load_json(path: str):
    with open(path) as f:
        return json.load(f)


def load_manifest(data_dir: str) -> dict:
    """Read `data_manifest.json`. Files generated by prepare_data.py are stored relative to the
    manifest so the folder still works when a later Kaggle notebook mounts it read-only elsewhere."""
    def resolve(v):
        if isinstance(v, dict):
            return {k: resolve(x) for k, x in v.items()}
        if isinstance(v, str) and not os.path.isabs(v):
            return os.path.join(data_dir, v)
        return v

    return resolve(load_json(os.path.join(data_dir, "data_manifest.json")))
